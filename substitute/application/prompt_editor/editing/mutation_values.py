"""Normalize numeric values supplied to prompt mutation operations."""

from __future__ import annotations

from decimal import Decimal


def prompt_decimal(value: float | Decimal) -> Decimal:
    """Convert one numeric editor value without binary-float artifacts."""

    if isinstance(value, Decimal):
        return value
    return Decimal(str(value))


__all__ = ["prompt_decimal"]
